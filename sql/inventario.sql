        RAISE EXCEPTION 'Catálogo desconocido' USING ERRCODE = '22023';
    END IF;
END;
$$;

-- Registra o modifica un nombre del catálogo.
CREATE OR REPLACE PROCEDURE public.sp_guardar_catalogo(
    IN p_entidad text, IN p_clave text, IN p_revision integer, IN p_nombre text,
    IN p_tipo text, IN p_version text, OUT p_clave_guardada text
) LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(718511);
    IF p_entidad = 'software' THEN
        IF p_clave IS NULL THEN
            INSERT INTO public.software(nombre_software, tipo, version)
            VALUES(btrim(p_nombre), nullif(btrim(p_tipo), ''), nullif(btrim(p_version), ''))
            RETURNING id_software::text INTO p_clave_guardada;
        ELSE
            UPDATE public.software SET nombre_software = btrim(p_nombre),
                tipo = nullif(btrim(p_tipo), ''), version = nullif(btrim(p_version), '')
            WHERE id_software = p_clave::integer AND revision = p_revision AND activo
            RETURNING id_software::text INTO p_clave_guardada;
        END IF;
    ELSIF p_entidad = 'componente' THEN
        IF p_clave IS NULL THEN
            INSERT INTO public.componente(nombre_componente) VALUES(btrim(p_nombre))
            RETURNING id_componente::text INTO p_clave_guardada;
        ELSE
            UPDATE public.componente SET nombre_componente = btrim(p_nombre)
            WHERE id_componente = p_clave::integer AND revision = p_revision AND activo
            RETURNING id_componente::text INTO p_clave_guardada;
        END IF;
    ELSE
        RAISE EXCEPTION 'Catálogo desconocido' USING ERRCODE = '22023';
    END IF;
    IF p_clave_guardada IS NULL THEN
        RAISE EXCEPTION 'El registro cambió o está inactivo. Actualice la consulta' USING ERRCODE = '40001';
    END IF;
END;
$$;

-- Cambia la actividad de un registro del catálogo.
CREATE OR REPLACE PROCEDURE public.sp_actividad_catalogo(
    IN p_entidad text, IN p_clave text, IN p_revision integer, IN p_activo boolean
) LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(718511);
    IF p_entidad = 'software' THEN
        UPDATE public.software SET activo = p_activo
        WHERE id_software = p_clave::integer AND revision = p_revision AND activo <> p_activo;
    ELSIF p_entidad = 'componente' THEN
        UPDATE public.componente SET activo = p_activo
        WHERE id_componente = p_clave::integer AND revision = p_revision AND activo <> p_activo;
    ELSE
        RAISE EXCEPTION 'Catálogo desconocido' USING ERRCODE = '22023';
    END IF;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El registro cambió. Actualice la consulta' USING ERRCODE = '40001';
    END IF;
END;
$$;

-- Muestra el software y los componentes de un equipo.
CREATE OR REPLACE PROCEDURE public.sp_listar_detalles(IN p_equipo integer, INOUT p_resultado refcursor)
LANGUAGE plpgsql AS $$
BEGIN
    OPEN p_resultado FOR
        SELECT 'software' AS entidad, s.id_software::text AS clave,
            s.nombre_software || coalesce(' ' || s.version, '') AS nombre,
            ti.fecha_instalacion::text AS detalle
        FROM public.tiene_instalado ti JOIN public.software s USING(id_software)
        WHERE ti.id_equipo = p_equipo
        UNION ALL
        SELECT 'componente', c.id_componente::text, c.nombre_componente, ec.detalle
        FROM public.equipo_componente ec JOIN public.componente c USING(id_componente)
        WHERE ec.id_equipo = p_equipo
        ORDER BY entidad, nombre;
END;
$$;

-- El detalle se guarda en la relación con el equipo.
-- Guarda la instalación o la especificación de cada equipo.
CREATE OR REPLACE PROCEDURE public.sp_vincular_detalle(
    IN p_equipo integer, IN p_entidad text, IN p_clave text, IN p_fecha date,
    IN p_accion text, IN p_fecha_anterior date, IN p_detalle text, IN p_detalle_anterior text
) LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(718511);
    IF NOT EXISTS (SELECT FROM public.equipo WHERE id_equipo = p_equipo AND activo) THEN
        RAISE EXCEPTION 'El equipo debe estar activo' USING ERRCODE = '23514';
    END IF;
    IF p_entidad = 'software' THEN
        CASE p_accion
        WHEN 'agregar' THEN
            INSERT INTO public.tiene_instalado VALUES(p_equipo, p_clave::integer, p_fecha);
        WHEN 'modificar' THEN
            UPDATE public.tiene_instalado SET fecha_instalacion = p_fecha
            WHERE id_equipo = p_equipo AND id_software = p_clave::integer
              AND fecha_instalacion IS NOT DISTINCT FROM p_fecha_anterior;
            IF NOT FOUND THEN RAISE EXCEPTION 'La instalación cambió' USING ERRCODE = '40001'; END IF;
        WHEN 'quitar' THEN
            DELETE FROM public.tiene_instalado WHERE id_equipo = p_equipo AND id_software = p_clave::integer
              AND fecha_instalacion IS NOT DISTINCT FROM p_fecha_anterior;
            IF NOT FOUND THEN RAISE EXCEPTION 'La instalación cambió' USING ERRCODE = '40001'; END IF;
        ELSE RAISE EXCEPTION 'Acción desconocida' USING ERRCODE = '22023';
        END CASE;
    ELSIF p_entidad = 'componente' THEN
        CASE p_accion
        WHEN 'agregar' THEN
            INSERT INTO public.equipo_componente(id_equipo, id_componente, detalle)
            VALUES(p_equipo, p_clave::integer, nullif(btrim(p_detalle), ''));
        WHEN 'modificar' THEN
            UPDATE public.equipo_componente SET detalle = nullif(btrim(p_detalle), '')
            WHERE id_equipo = p_equipo AND id_componente = p_clave::integer
              AND detalle IS NOT DISTINCT FROM p_detalle_anterior;
            IF NOT FOUND THEN RAISE EXCEPTION 'El componente cambió' USING ERRCODE = '40001'; END IF;
        WHEN 'quitar' THEN
            DELETE FROM public.equipo_componente WHERE id_equipo = p_equipo AND id_componente = p_clave::integer
              AND detalle IS NOT DISTINCT FROM p_detalle_anterior;
            IF NOT FOUND THEN RAISE EXCEPTION 'La asociación cambió' USING ERRCODE = '40001'; END IF;
        ELSE RAISE EXCEPTION 'Acción desconocida' USING ERRCODE = '22023';
        END CASE;
    ELSE RAISE EXCEPTION 'Detalle desconocido' USING ERRCODE = '22023';
    END IF;
END;
$$;

-- Consulta los últimos cambios registrados.
CREATE OR REPLACE PROCEDURE public.sp_auditoria_inventario(IN p_filtro text, INOUT p_resultado refcursor)
LANGUAGE plpgsql AS $$
BEGIN
    OPEN p_resultado FOR SELECT id_auditoria, fecha, usuario, tabla, operacion, clave,
        anterior::text, nuevo::text FROM public.auditoria_inventario
        WHERE coalesce(btrim(p_filtro), '') = ''
           OR strpos(lower(clave), lower(btrim(p_filtro))) > 0
        ORDER BY id_auditoria DESC LIMIT 200;
END;
$$;

-- Agrupa los detalles para mostrar una sola ficha por equipo.
-- Reúne los datos completos de la hoja de vida.
CREATE OR REPLACE PROCEDURE public.sp_hoja_vida_equipo(
    IN p_codigo text,
    INOUT p_resultado refcursor
)
LANGUAGE plpgsql
AS $$
BEGIN
    OPEN p_resultado FOR
        SELECT e.codigo_inventario, e.nombre_equipo, t.tipo, m.nombre_marca, e.modelo,
               e.numero_serie, host(e.direccion_ip) AS ip, es.estado, o.nombre_oficina,
               a.nombre_area, pe.nombres_empleado AS asignado_a, e.fecha_compra, e.garantia,
               p.lista AS perifericos, c.lista AS componentes, s.lista AS software
        FROM public.equipo e
        JOIN public.tipo_equipo t USING (id_tipo)
        JOIN public.estado es USING (id_estado)
        LEFT JOIN public.marca m USING (id_marca)
        LEFT JOIN public.oficina o USING (id_oficina)
        LEFT JOIN public.area a ON a.id_area = e.id_area
        LEFT JOIN public.empleado pe ON pe.id_empleado = e.id_empleado
        LEFT JOIN LATERAL (
            SELECT array_agg(
                tp.tipo || ' ' || coalesce(ep.modelo, 'Sin modelo') ||
                ' [serie: ' || coalesce(ep.numero_serie, 'No consignada') || ']'
                ORDER BY ep.id_equipo
            ) AS lista
            FROM public.equipo ep
            JOIN public.tipo_equipo tp USING (id_tipo)
            WHERE ep.id_equipo_principal = e.id_equipo AND ep.activo
        ) p ON true
        LEFT JOIN LATERAL (
            SELECT array_agg(
                co.nombre_componente || ': ' || coalesce(ec.detalle, 'No consignado')
                ORDER BY co.nombre_componente
            ) AS lista
            FROM public.equipo_componente ec
            JOIN public.componente co USING (id_componente)
            WHERE ec.id_equipo = e.id_equipo AND co.activo
        ) c ON true
        LEFT JOIN LATERAL (
            SELECT array_agg(
                so.nombre_software || coalesce(' ' || so.version, '') ||
                ' [instalación: ' || coalesce(ti.fecha_instalacion::text, 'No consignada') || ']'
                ORDER BY so.id_software
            ) AS lista
            FROM public.tiene_instalado ti
            JOIN public.software so USING (id_software)
            WHERE ti.id_equipo = e.id_equipo AND so.activo
        ) s ON true
        WHERE e.codigo_inventario = p_codigo AND e.activo;
END;
$$;

