-- Consultas disponibles desde la pantalla Reportes.
-- Ejecuta uno de los 15 reportes con su filtro.
CREATE OR REPLACE PROCEDURE public.sp_reporte(
    IN p_numero integer, IN p_filtro text, IN p_fecha date, IN p_dias integer,
    INOUT p_resultado refcursor
) LANGUAGE plpgsql AS $$
BEGIN
    IF p_fecha IS NULL OR p_dias NOT BETWEEN 1 AND 3650 THEN
        RAISE EXCEPTION 'Revise la fecha y el plazo del reporte' USING ERRCODE = '22023';
    END IF;
    CASE p_numero
    -- 01. Hoja de vida completa de un equipo, sin multiplicar sus detalles
    WHEN 1 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT e.codigo_inventario, e.nombre_equipo, t.tipo, m.nombre_marca, e.modelo,
       e.numero_serie, host(e.direccion_ip) AS ip, es.estado,
       o.nombre_oficina, a.nombre_area, pe.nombres_empleado AS asignado_a,
       e.fecha_compra, e.garantia,
       COALESCE(p.lista,'Sin periféricos registrados') AS perifericos,
       COALESCE(c.lista,'Sin componentes registrados') AS componentes,
       COALESCE(s.lista,'Sin software registrado') AS software
FROM (SELECT * FROM public.equipo WHERE activo) e
JOIN public.tipo_equipo t ON t.id_tipo=e.id_tipo
JOIN public.estado es ON es.id_estado=e.id_estado
LEFT JOIN public.marca m ON m.id_marca=e.id_marca
LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina
LEFT JOIN public.area a ON a.id_area=e.id_area
LEFT JOIN public.empleado pe ON pe.id_empleado=e.id_empleado
LEFT JOIN LATERAL (
 SELECT string_agg(tp.tipo||' '||COALESCE(ep.modelo,'Sin modelo')||
                  ' [serie: '||COALESCE(ep.numero_serie,'No consignada')||']',
                  ' | ' ORDER BY ep.id_equipo) AS lista
 FROM (SELECT * FROM public.equipo WHERE activo) ep JOIN public.tipo_equipo tp ON tp.id_tipo=ep.id_tipo
 WHERE ep.id_equipo_principal=e.id_equipo
) p ON true
LEFT JOIN LATERAL (
 SELECT string_agg(co.nombre_componente||': '||COALESCE(ec.detalle,'No consignado'),
                   ' | ' ORDER BY co.nombre_componente) AS lista
 FROM public.equipo_componente ec JOIN (SELECT * FROM public.componente WHERE activo) co USING(id_componente)
 WHERE ec.id_equipo=e.id_equipo
) c ON true
LEFT JOIN LATERAL (
 SELECT string_agg(so.nombre_software||COALESCE(' '||so.version,'')||
                  ' [instalación: '||COALESCE(ti.fecha_instalacion::text,'No consignada')||']',
                  ' | ' ORDER BY so.id_software) AS lista
 FROM public.tiene_instalado ti JOIN (SELECT * FROM public.software WHERE activo) so USING(id_software)
 WHERE ti.id_equipo=e.id_equipo
) s ON true

        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 02. Resumen por oficina con equipos principales y periféricos separados
    WHEN 2 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT o.id_oficina, o.nombre_oficina, COUNT(e.id_equipo) AS activos_registrados,
 COUNT(e.id_equipo) FILTER (WHERE t.tipo IN ('Computadora','Laptop','Servidor')) AS equipos_de_computo,
 COUNT(e.id_equipo) FILTER (WHERE t.tipo IN ('Monitor','Teclado','Mouse')) AS perifericos,
 COUNT(e.id_equipo) FILTER (WHERE es.estado LIKE 'Inoperativo%') AS inoperativos,
 COUNT(e.id_equipo) FILTER (WHERE e.id_empleado IS NULL) AS sin_asignado
FROM public.oficina o
LEFT JOIN (SELECT * FROM public.equipo WHERE activo) e ON e.id_oficina=o.id_oficina
LEFT JOIN public.tipo_equipo t ON t.id_tipo=e.id_tipo
LEFT JOIN public.estado es ON es.id_estado=e.id_estado
GROUP BY o.id_oficina,o.nombre_oficina ORDER BY activos_registrados DESC,o.id_oficina
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 03. Ubicación y características de los inoperativos por reparar
    WHEN 3 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT e.codigo_inventario,t.tipo,m.nombre_marca,e.modelo,o.nombre_oficina,
 a.nombre_area,pe.nombres_empleado, e.numero_serie,
 string_agg(co.nombre_componente||': '||COALESCE(ec.detalle,'No consignado'),
            ' | ' ORDER BY co.nombre_componente) AS configuracion_registrada
FROM public.estado es JOIN (SELECT * FROM public.equipo WHERE activo) e ON e.id_estado=es.id_estado
JOIN public.tipo_equipo t ON t.id_tipo=e.id_tipo
LEFT JOIN public.marca m ON m.id_marca=e.id_marca
LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina
LEFT JOIN public.area a ON a.id_area=e.id_area
LEFT JOIN public.empleado pe ON pe.id_empleado=e.id_empleado
LEFT JOIN public.equipo_componente ec ON ec.id_equipo=e.id_equipo
LEFT JOIN (SELECT * FROM public.componente WHERE activo) co USING(id_componente)
WHERE es.estado='Inoperativo por reparar'
GROUP BY e.id_equipo,e.codigo_inventario,e.modelo,e.numero_serie,t.tipo,m.nombre_marca,o.nombre_oficina,a.nombre_area,pe.nombres_empleado
ORDER BY t.tipo,o.nombre_oficina,e.codigo_inventario
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 04. Puestos de cómputo sin trabajador consignado
    WHEN 4 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT e.codigo_inventario,e.nombre_equipo,t.tipo,es.estado,o.nombre_oficina,
 a.nombre_area,enc.nombres_empleado AS encargado_area_para_consultar
FROM (SELECT * FROM public.equipo WHERE activo) e JOIN public.tipo_equipo t USING(id_tipo)
JOIN public.estado es USING(id_estado)
LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina
LEFT JOIN public.area a ON a.id_area=e.id_area
LEFT JOIN public.empleado enc ON enc.id_empleado=a.id_empleado
WHERE e.id_empleado IS NULL AND t.tipo IN ('Computadora','Laptop')
ORDER BY o.nombre_oficina,e.codigo_inventario
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 05. Datos de identificación pendientes de verificación física
    WHEN 5 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT e.codigo_inventario,t.tipo,o.nombre_oficina,
 concat_ws('; ',
  CASE WHEN NULLIF(btrim(e.modelo),'') IS NULL THEN 'Modelo no consignado' END,
  CASE WHEN NULLIF(btrim(e.numero_serie),'') IS NULL THEN 'Serie no consignada' END,
  CASE WHEN e.id_marca IS NULL THEN 'Marca no consignada' END,
  CASE WHEN e.id_oficina IS NULL THEN 'Oficina no consignada' END) AS por_verificar
FROM (SELECT * FROM public.equipo WHERE activo) e JOIN public.tipo_equipo t USING(id_tipo)
LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina
WHERE NULLIF(btrim(e.modelo),'') IS NULL OR NULLIF(btrim(e.numero_serie),'') IS NULL
 OR e.id_marca IS NULL OR e.id_oficina IS NULL
ORDER BY t.tipo,e.codigo_inventario
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 06. Direcciones IP repetidas en el inventario actual
    WHEN 6 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT host(e.direccion_ip) AS ip, COUNT(*) AS equipos,
 string_agg(e.codigo_inventario||' - '||COALESCE(o.nombre_oficina,'Sin oficina'),
            ' | ' ORDER BY e.codigo_inventario) AS ubicaciones
FROM (SELECT * FROM public.equipo WHERE activo) e LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina
WHERE e.direccion_ip IS NOT NULL
GROUP BY host(e.direccion_ip) HAVING COUNT(*)>1 ORDER BY equipos DESC,ip
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 07. Garantías vigentes próximas a vencer en 90 días
    WHEN 7 THEN
        OPEN p_resultado FOR SELECT * FROM (
WITH parametros AS (SELECT p_fecha AS fecha_corte,p_dias AS dias)
SELECT e.codigo_inventario,t.tipo,m.nombre_marca,e.modelo,o.nombre_oficina,
 e.fecha_compra,e.garantia,e.garantia-p.fecha_corte AS dias_restantes
FROM (SELECT * FROM public.equipo WHERE activo) e CROSS JOIN parametros p
JOIN public.tipo_equipo t USING(id_tipo)
LEFT JOIN public.marca m USING(id_marca)
LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina
WHERE e.garantia>=p.fecha_corte AND e.garantia<=p.fecha_corte+p.dias
ORDER BY e.garantia,e.codigo_inventario
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 08. Antigüedad conocida y cobertura de las fechas de compra por oficina
    WHEN 8 THEN
        OPEN p_resultado FOR SELECT * FROM (
WITH parametros AS (SELECT p_fecha AS fecha_corte)
SELECT o.nombre_oficina, COUNT(*) AS puestos,
 COUNT(*) FILTER (WHERE e.fecha_compra IS NULL) AS sin_fecha_compra,
 COUNT(*) FILTER (WHERE e.fecha_compra<=p.fecha_corte-INTERVAL '8 years') AS con_8_anos_o_mas,
 ROUND(AVG(EXTRACT(YEAR FROM age(p.fecha_corte,e.fecha_compra)))::numeric,1) AS promedio_anos_conocidos
FROM (SELECT * FROM public.equipo WHERE activo) e JOIN public.tipo_equipo t USING(id_tipo)
LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina CROSS JOIN parametros p
WHERE t.tipo IN ('Computadora','Laptop')
GROUP BY o.id_oficina,o.nombre_oficina ORDER BY con_8_anos_o_mas DESC,o.id_oficina
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 09. Cobertura documental de sistema operativo, ofimática y antivirus
    WHEN 9 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT e.codigo_inventario,o.nombre_oficina,
 CASE WHEN EXISTS(SELECT 1 FROM public.tiene_instalado ti JOIN (SELECT * FROM public.software WHERE activo) s USING(id_software)
                  WHERE ti.id_equipo=e.id_equipo AND s.tipo='Sistema Operativo')
      THEN 'Registrado' ELSE 'Sin registro' END AS sistema_operativo,
 CASE WHEN EXISTS(SELECT 1 FROM public.tiene_instalado ti JOIN (SELECT * FROM public.software WHERE activo) s USING(id_software)
                  WHERE ti.id_equipo=e.id_equipo AND s.tipo='Ofimática')
      THEN 'Registrado' ELSE 'Sin registro' END AS ofimatica,
 CASE WHEN EXISTS(SELECT 1 FROM public.tiene_instalado ti JOIN (SELECT * FROM public.software WHERE activo) s USING(id_software)
                  WHERE ti.id_equipo=e.id_equipo AND s.tipo='Antivirus')
      THEN 'Registrado' ELSE 'Sin registro' END AS antivirus
FROM (SELECT * FROM public.equipo WHERE activo) e JOIN public.tipo_equipo t USING(id_tipo)
LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina
WHERE t.tipo IN ('Computadora','Laptop') ORDER BY e.codigo_inventario
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 10. Distribución de versiones Windows y Office registradas
    WHEN 10 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT s.nombre_software,s.version,o.nombre_oficina,COUNT(*) AS instalaciones,
 COUNT(*) FILTER(WHERE ti.fecha_instalacion IS NULL) AS fechas_no_consignadas
FROM (SELECT * FROM public.software WHERE activo) s JOIN public.tiene_instalado ti USING(id_software)
JOIN (SELECT * FROM public.equipo WHERE activo) e ON e.id_equipo=ti.id_equipo
LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina
WHERE s.nombre_software IN ('Windows','Microsoft Office')
GROUP BY s.id_software,s.nombre_software,s.version,o.id_oficina,o.nombre_oficina
ORDER BY s.nombre_software,s.version,o.id_oficina
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 11. Carga de equipos asignados por trabajador y supervisor
    WHEN 11 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT pe.id_empleado,pe.nombres_empleado,ca.cargo,o.nombre_oficina,
 sup.nombres_empleado AS supervisor,COUNT(e.id_equipo) AS activos,
 COUNT(e.id_equipo) FILTER(WHERE t.tipo IN ('Computadora','Laptop')) AS puestos_de_computo,
 COUNT(e.id_equipo) FILTER(WHERE t.tipo IN ('Monitor','Teclado','Mouse')) AS perifericos
FROM public.empleado pe LEFT JOIN public.cargo_empleado ca USING(id_cargo)
LEFT JOIN public.oficina o ON o.id_oficina=pe.id_oficina
LEFT JOIN public.empleado sup ON sup.id_empleado=pe.id_empleado_supervisor
LEFT JOIN (SELECT * FROM public.equipo WHERE activo) e ON e.id_empleado=pe.id_empleado
LEFT JOIN public.tipo_equipo t ON t.id_tipo=e.id_tipo
GROUP BY pe.id_empleado,ca.cargo,o.nombre_oficina,sup.nombres_empleado
ORDER BY activos DESC,pe.id_empleado
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 12. Periféricos con conexión o ubicación pendiente de comprobar
    WHEN 12 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT e.codigo_inventario,t.tipo,e.modelo,o.nombre_oficina,
 p.codigo_inventario AS equipo_principal,op.nombre_oficina AS oficina_principal,
 CASE WHEN e.id_equipo_principal IS NULL THEN 'Conexión no consignada'
      WHEN e.id_oficina IS DISTINCT FROM p.id_oficina THEN 'Oficinas distintas: comprobar'
      ELSE 'Revisar' END AS observacion
FROM (SELECT * FROM public.equipo WHERE activo) e JOIN public.tipo_equipo t USING(id_tipo)
LEFT JOIN (SELECT * FROM public.equipo WHERE activo) p ON p.id_equipo=e.id_equipo_principal
LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina
LEFT JOIN public.oficina op ON op.id_oficina=p.id_oficina
WHERE t.tipo IN ('Monitor','Teclado','Mouse')
 AND (e.id_equipo_principal IS NULL OR e.id_oficina IS DISTINCT FROM p.id_oficina)
ORDER BY e.codigo_inventario
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 13. Puestos con memoria registrada inferior a 8 GB
    WHEN 13 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT e.codigo_inventario,e.modelo,es.estado,o.nombre_oficina,
 co.nombre_componente,ec.detalle AS memoria_registrada
FROM (SELECT * FROM public.componente WHERE activo) co JOIN public.equipo_componente ec USING(id_componente)
JOIN (SELECT * FROM public.equipo WHERE activo) e ON e.id_equipo=ec.id_equipo
JOIN public.tipo_equipo t USING(id_tipo) JOIN public.estado es USING(id_estado)
LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina
WHERE co.nombre_componente LIKE 'Memoria RAM%'
 AND ec.detalle ~ '^[0-9]+([.][0-9]+)? GB$'
 AND nullif(substring(ec.detalle FROM '^([0-9]+[.]?[0-9]*) GB$'), '')::numeric<8
 AND t.tipo IN ('Computadora','Laptop')
ORDER BY e.codigo_inventario
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 14. Fechas de compra o garantía no disponibles, sin inventar antigüedad
    WHEN 14 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT o.nombre_oficina,t.tipo,COUNT(*) AS equipos,
 COUNT(*) FILTER(WHERE e.fecha_compra IS NULL) AS sin_fecha_compra,
 COUNT(*) FILTER(WHERE e.garantia IS NULL) AS sin_fin_garantia,
 COUNT(*) FILTER(WHERE e.fecha_compra IS NOT NULL AND e.garantia IS NOT NULL
                       AND e.garantia<e.fecha_compra) AS fechas_invertidas
FROM (SELECT * FROM public.equipo WHERE activo) e JOIN public.tipo_equipo t USING(id_tipo)
LEFT JOIN public.oficina o ON o.id_oficina=e.id_oficina
GROUP BY o.id_oficina,o.nombre_oficina,t.id_tipo,t.tipo
HAVING COUNT(*) FILTER(WHERE e.fecha_compra IS NULL OR e.garantia IS NULL
                     OR e.garantia<e.fecha_compra)>0
ORDER BY o.id_oficina,t.id_tipo
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    -- 15. Utilización del catálogo de software, incluidas versiones sin instalación
    WHEN 15 THEN
        OPEN p_resultado FOR SELECT * FROM (
SELECT s.id_software,s.nombre_software,s.tipo,s.version,
 COUNT(ti.id_equipo) AS equipos_con_instalacion,
 COUNT(ti.id_equipo) FILTER(WHERE ti.fecha_instalacion IS NULL) AS sin_fecha,
 MIN(ti.fecha_instalacion) AS primera_fecha_conocida,
 MAX(ti.fecha_instalacion) AS ultima_fecha_conocida
FROM (SELECT * FROM public.software WHERE activo) s LEFT JOIN public.tiene_instalado ti USING(id_software)
GROUP BY s.id_software,s.nombre_software,s.tipo,s.version
ORDER BY equipos_con_instalacion DESC,s.id_software
        ) r WHERE coalesce(btrim(p_filtro), '') = ''
             OR EXISTS(SELECT FROM jsonb_each_text(to_jsonb(r)) campo WHERE strpos(lower(campo.value), lower(btrim(p_filtro))) > 0);
    ELSE RAISE EXCEPTION 'Reporte desconocido' USING ERRCODE = '22023';
    END CASE;
END;
