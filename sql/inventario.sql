-- Busca equipos por código, nombre o modelo.
CREATE OR REPLACE PROCEDURE public.sp_listar_inventario(
    IN p_filtro text, IN p_inactivos boolean, INOUT p_resultado refcursor
) LANGUAGE plpgsql AS $$
DECLARE v_filtro text := lower(btrim(coalesce(p_filtro, '')));
BEGIN
    OPEN p_resultado FOR
        SELECT e.*, host(e.direccion_ip) AS ip, t.tipo, es.estado,
               o.nombre_oficina, a.nombre_area, pe.nombres_empleado, m.nombre_marca
        FROM public.equipo e
        JOIN public.tipo_equipo t USING(id_tipo)
        JOIN public.estado es USING(id_estado)
        LEFT JOIN public.oficina o USING(id_oficina)
        LEFT JOIN public.area a ON a.id_area = e.id_area
        LEFT JOIN public.empleado pe ON pe.id_empleado = e.id_empleado
        LEFT JOIN public.marca m USING(id_marca)
        WHERE (e.activo OR p_inactivos)
          AND (v_filtro = '' OR strpos(lower(e.codigo_inventario), v_filtro) > 0
               OR strpos(lower(e.nombre_equipo), v_filtro) > 0 OR strpos(lower(e.modelo), v_filtro) > 0)
        ORDER BY e.codigo_inventario;
END;
$$;

-- Reúne las opciones del formulario de equipos.
CREATE OR REPLACE PROCEDURE public.sp_catalogos_equipo(INOUT p_resultado refcursor)
LANGUAGE plpgsql AS $$
BEGIN
    OPEN p_resultado FOR
        SELECT 'tipo' AS catalogo, id_tipo AS id, tipo AS nombre FROM public.tipo_equipo
        UNION ALL SELECT 'estado', id_estado, estado FROM public.estado
        UNION ALL SELECT 'oficina', id_oficina, nombre_oficina FROM public.oficina
        UNION ALL SELECT 'area', id_area, nombre_area FROM public.area
        UNION ALL SELECT 'empleado', id_empleado, nombres_empleado FROM public.empleado
        UNION ALL SELECT 'marca', id_marca, nombre_marca FROM public.marca
        UNION ALL SELECT 'principal', id_equipo, codigo_inventario || ' · ' || coalesce(nombre_equipo, '') FROM public.equipo WHERE activo
        ORDER BY catalogo, nombre, id;
END;
$$;

-- Registra o modifica un equipo y controla su revisión.
CREATE OR REPLACE PROCEDURE public.sp_guardar_equipo(
    IN p_id integer, IN p_revision integer, IN p_codigo text, IN p_nombre text,
    IN p_modelo text, IN p_serie text, IN p_tipo integer, IN p_estado integer,
    IN p_oficina integer, IN p_area integer, IN p_empleado integer, IN p_marca integer,
    IN p_principal integer, IN p_ip text, IN p_compra date, IN p_garantia date,
    OUT p_id_guardado integer
) LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(718511);
    IF p_id IS NULL THEN
        INSERT INTO public.equipo(codigo_inventario, nombre_equipo, modelo, numero_serie,
            id_tipo, id_estado, id_oficina, id_area, id_empleado, id_marca, id_equipo_principal,
            direccion_ip, fecha_compra, garantia)
        VALUES(btrim(p_codigo), nullif(btrim(p_nombre), ''), nullif(btrim(p_modelo), ''),
            nullif(btrim(p_serie), ''), p_tipo, p_estado, p_oficina, p_area, p_empleado, p_marca,
            p_principal, nullif(btrim(p_ip), '')::inet, p_compra, p_garantia)
        RETURNING id_equipo INTO p_id_guardado;
    ELSE
        UPDATE public.equipo SET codigo_inventario = btrim(p_codigo), nombre_equipo = nullif(btrim(p_nombre), ''),
            modelo = nullif(btrim(p_modelo), ''), numero_serie = nullif(btrim(p_serie), ''),
            id_tipo = p_tipo, id_estado = p_estado, id_oficina = p_oficina, id_area = p_area,
            id_empleado = p_empleado, id_marca = p_marca, id_equipo_principal = p_principal,
            direccion_ip = nullif(btrim(p_ip), '')::inet, fecha_compra = p_compra, garantia = p_garantia
        WHERE id_equipo = p_id AND revision = p_revision AND activo
        RETURNING id_equipo INTO p_id_guardado;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'El equipo cambió o está inactivo. Actualice la consulta' USING ERRCODE = '40001';
        END IF;
    END IF;
END;
$$;

-- Desactiva o reactiva un equipo sin eliminarlo.
CREATE OR REPLACE PROCEDURE public.sp_actividad_equipo(IN p_id integer, IN p_revision integer, IN p_activo boolean)
LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(718511);
    UPDATE public.equipo SET activo = p_activo
    WHERE id_equipo = p_id AND revision = p_revision AND activo <> p_activo;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El equipo cambió. Actualice la consulta' USING ERRCODE = '40001';
    END IF;
END;
$$;

-- Consulta el catálogo de software o componentes.
CREATE OR REPLACE PROCEDURE public.sp_listar_catalogo(
    IN p_entidad text, IN p_inactivos boolean, INOUT p_resultado refcursor
) LANGUAGE plpgsql AS $$
BEGIN
    IF p_entidad = 'software' THEN
        OPEN p_resultado FOR SELECT id_software::text AS clave, nombre_software AS nombre,
            tipo, version, activo, revision FROM public.software
            WHERE activo OR p_inactivos ORDER BY nombre_software, id_software;
