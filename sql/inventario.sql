-- Guarda los valores anteriores y nuevos en el historial.
CREATE OR REPLACE FUNCTION public.fn_auditar_inventario() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_anterior jsonb;
    v_nuevo jsonb;
    v_fila jsonb;
    v_operacion text := TG_OP;
BEGIN
    IF TG_OP <> 'INSERT' THEN v_anterior := to_jsonb(OLD); END IF;
    IF TG_OP <> 'DELETE' THEN v_nuevo := to_jsonb(NEW); END IF;
    IF TG_OP = 'UPDATE' AND v_anterior = v_nuevo THEN RETURN NULL; END IF;
    IF TG_OP = 'UPDATE' AND v_anterior->>'activo' = 'true' AND v_nuevo->>'activo' = 'false' THEN
        v_operacion := 'DESACTIVAR';
    ELSIF TG_OP = 'UPDATE' AND v_anterior->>'activo' = 'false' AND v_nuevo->>'activo' = 'true' THEN
        v_operacion := 'REACTIVAR';
    END IF;
    v_fila := coalesce(v_nuevo, v_anterior);
    INSERT INTO public.auditoria_inventario(tabla, operacion, clave, anterior, nuevo)
    VALUES (TG_TABLE_NAME, v_operacion,
        coalesce(v_fila->>'codigo_inventario',
            concat_ws(' / ', v_fila->>'id_equipo', v_fila->>'id_software',
                      v_fila->>'id_componente')), v_anterior, v_nuevo);
    RETURN NULL;
END;
$$;

-- Comprueba fechas, equipo principal y referencias activas.
CREATE OR REPLACE FUNCTION public.fn_validar_equipo() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.fecha_compra IS NOT NULL AND NEW.garantia < NEW.fecha_compra THEN
        RAISE EXCEPTION 'La garantía no puede terminar antes de la compra' USING ERRCODE = '23514';
    END IF;
    IF nullif(btrim(NEW.codigo_inventario), '') IS NULL THEN
        RAISE EXCEPTION 'El código es obligatorio' USING ERRCODE = '22023';
    END IF;
    IF NEW.activo AND NEW.id_equipo_principal IS NOT NULL THEN
        IF NOT EXISTS (SELECT FROM public.equipo WHERE id_equipo = NEW.id_equipo_principal AND activo) THEN
            RAISE EXCEPTION 'El equipo principal debe estar activo' USING ERRCODE = '23514';
        END IF;
        IF EXISTS (
            WITH RECURSIVE ascendientes AS (
                SELECT id_equipo, id_equipo_principal FROM public.equipo WHERE id_equipo = NEW.id_equipo_principal
                UNION
                SELECT e.id_equipo, e.id_equipo_principal FROM public.equipo e
                JOIN ascendientes a ON e.id_equipo = a.id_equipo_principal
            )
            SELECT FROM ascendientes WHERE id_equipo = NEW.id_equipo
        ) THEN
            RAISE EXCEPTION 'La conexión entre equipos produciría un ciclo' USING ERRCODE = '23514';
        END IF;
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.activo AND NOT NEW.activo AND EXISTS (
        SELECT FROM public.equipo WHERE id_equipo_principal = OLD.id_equipo AND activo
    ) THEN
        RAISE EXCEPTION 'Desvincule primero los periféricos activos' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND NOT OLD.activo AND NEW.activo AND (
        EXISTS (SELECT FROM public.tiene_instalado ti JOIN public.software s USING(id_software)
                WHERE ti.id_equipo = NEW.id_equipo AND NOT s.activo)
        OR EXISTS (SELECT FROM public.equipo_componente ec JOIN public.componente c USING(id_componente)
                   WHERE ec.id_equipo = NEW.id_equipo AND NOT c.activo)
    ) THEN
        RAISE EXCEPTION 'Reactive primero el software y los componentes vinculados' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

-- Impide desactivar software o componentes que siguen en uso.
CREATE OR REPLACE FUNCTION public.fn_validar_catalogo() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'software' THEN
        IF nullif(btrim(NEW.nombre_software), '') IS NULL THEN
            RAISE EXCEPTION 'El nombre es obligatorio' USING ERRCODE = '22023';
        END IF;
        IF TG_OP = 'UPDATE' AND OLD.activo AND NOT NEW.activo AND EXISTS (
            SELECT FROM public.tiene_instalado ti JOIN public.equipo e USING(id_equipo)
            WHERE ti.id_software = OLD.id_software AND e.activo
        ) THEN
            RAISE EXCEPTION 'Retire primero las instalaciones en equipos activos' USING ERRCODE = '23514';
        END IF;
    ELSE
        IF nullif(btrim(NEW.nombre_componente), '') IS NULL THEN
            RAISE EXCEPTION 'El nombre es obligatorio' USING ERRCODE = '22023';
        END IF;
        IF TG_OP = 'UPDATE' AND OLD.activo AND NOT NEW.activo AND EXISTS (
            SELECT FROM public.equipo_componente ec JOIN public.equipo e USING(id_equipo)
            WHERE ec.id_componente = OLD.id_componente AND e.activo
        ) THEN
            RAISE EXCEPTION 'Retire primero las asociaciones a equipos activos' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

-- Solo permite asociar equipos y registros activos.
CREATE OR REPLACE FUNCTION public.fn_validar_asociacion() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT FROM public.equipo WHERE id_equipo = NEW.id_equipo AND activo) THEN
