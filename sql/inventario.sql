ALTER TABLE public.equipo
    ADD CONSTRAINT fk_equipo_id_oficina
    FOREIGN KEY (id_oficina) REFERENCES public.oficina (id_oficina)
    ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE public.equipo
    ADD CONSTRAINT fk_equipo_id_marca
    FOREIGN KEY (id_marca) REFERENCES public.marca (id_marca)
    ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE public.equipo
    ADD CONSTRAINT fk_equipo_id_equipo_principal
    FOREIGN KEY (id_equipo_principal) REFERENCES public.equipo (id_equipo)
    ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE public.empleado
    ADD CONSTRAINT fk_empleado_id_cargo
    FOREIGN KEY (id_cargo) REFERENCES public.cargo_empleado (id_cargo)
    ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE public.empleado
    ADD CONSTRAINT fk_empleado_id_oficina
    FOREIGN KEY (id_oficina) REFERENCES public.oficina (id_oficina)
    ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE public.empleado
    ADD CONSTRAINT fk_empleado_id_empleado_supervisor
    FOREIGN KEY (id_empleado_supervisor) REFERENCES public.empleado (id_empleado)
    ON UPDATE NO ACTION ON DELETE NO ACTION;

