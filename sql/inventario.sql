-- Ejecutar en una base vacía llamada inventario_ti.
-- Incluye tablas, datos de prueba, procedimientos, triggers y 15 reportes.
BEGIN;
-- Tablas del inventario.

-- EQUIPO
CREATE TABLE public.equipo (
    id_equipo INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONSTRAINT ck_equipo_id_equipo CHECK (id_equipo > 0),
    nombre_equipo VARCHAR(80) NULL,
    modelo VARCHAR(80) NULL,
    id_estado INTEGER NOT NULL,
    id_tipo INTEGER NOT NULL,
    direccion_ip INET NULL,
    fecha_compra DATE NULL,
    garantia DATE NULL,
    numero_serie VARCHAR(80) NULL,
    codigo_inventario VARCHAR(20) NOT NULL,
    CONSTRAINT uq_equipo_codigo_inventario UNIQUE (codigo_inventario),
    id_empleado INTEGER NULL,
    id_area INTEGER NULL,
    id_oficina INTEGER NULL,
    id_marca INTEGER NULL,
    id_equipo_principal INTEGER NULL,
    CONSTRAINT pk_equipo PRIMARY KEY (id_equipo)
);

-- EMPLEADO
CREATE TABLE public.empleado (
    id_empleado INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONSTRAINT ck_empleado_id_empleado CHECK (id_empleado > 0),
    nombres_empleado VARCHAR(120) NOT NULL,
    id_cargo INTEGER NULL,
    id_oficina INTEGER NULL,
    id_empleado_supervisor INTEGER NULL,
    CONSTRAINT pk_empleado PRIMARY KEY (id_empleado)
);

-- AREA
CREATE TABLE public.area (
    id_area INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONSTRAINT ck_area_id_area CHECK (id_area > 0),
    nombre_area VARCHAR(120) NOT NULL,
    piso SMALLINT NULL,
    CONSTRAINT ck_area_piso CHECK (piso >= 0),
    id_empleado INTEGER NULL,
    CONSTRAINT pk_area PRIMARY KEY (id_area)
);

-- MARCA
CREATE TABLE public.marca (
    id_marca INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONSTRAINT ck_marca_id_marca CHECK (id_marca > 0),
    nombre_marca VARCHAR(80) NOT NULL,
    CONSTRAINT pk_marca PRIMARY KEY (id_marca)
);

-- OFICINA
CREATE TABLE public.oficina (
    id_oficina INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONSTRAINT ck_oficina_id_oficina CHECK (id_oficina > 0),
    nombre_oficina VARCHAR(150) NOT NULL,
    id_area INTEGER NULL,
    CONSTRAINT pk_oficina PRIMARY KEY (id_oficina)
);

-- ESTADO
CREATE TABLE public.estado (
    id_estado INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONSTRAINT ck_estado_id_estado CHECK (id_estado > 0),
    estado VARCHAR(60) NOT NULL,
    CONSTRAINT pk_estado PRIMARY KEY (id_estado)
);

-- CARGO_EMPLEADO
CREATE TABLE public.cargo_empleado (
    id_cargo INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONSTRAINT ck_cargo_empleado_id_cargo CHECK (id_cargo > 0),
    cargo VARCHAR(80) NOT NULL,
    CONSTRAINT pk_cargo_empleado PRIMARY KEY (id_cargo)
);

-- TIPO_EQUIPO
CREATE TABLE public.tipo_equipo (
    id_tipo INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONSTRAINT ck_tipo_equipo_id_tipo CHECK (id_tipo > 0),
    tipo VARCHAR(60) NOT NULL,
    CONSTRAINT pk_tipo_equipo PRIMARY KEY (id_tipo)
);

-- SOFTWARE
CREATE TABLE public.software (
    id_software INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONSTRAINT ck_software_id_software CHECK (id_software > 0),
    nombre_software VARCHAR(120) NOT NULL,
    tipo VARCHAR(80) NULL,
    version VARCHAR(60) NULL,
    CONSTRAINT pk_software PRIMARY KEY (id_software)
);

-- TIENE_INSTALADO
CREATE TABLE public.tiene_instalado (
    id_equipo INTEGER NOT NULL,
    id_software INTEGER NOT NULL,
    fecha_instalacion DATE NULL,
    CONSTRAINT pk_tiene_instalado PRIMARY KEY (id_equipo, id_software)
);

-- EQUIPO_COMPONENTE
CREATE TABLE public.equipo_componente (
    id_equipo INTEGER NOT NULL,
    id_componente INTEGER NOT NULL,
    detalle VARCHAR(200) NULL,
    CONSTRAINT pk_equipo_componente PRIMARY KEY (id_equipo, id_componente)
);

-- COMPONENTE
CREATE TABLE public.componente (
    id_componente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_componente VARCHAR(100) NOT NULL,
    CONSTRAINT ck_componente_id CHECK (id_componente > 0)
);

-- Relaciones entre las tablas.

